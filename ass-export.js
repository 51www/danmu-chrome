(function (global) {
  "use strict";

  const PLAY_RES_X = 1920;
  const PLAY_RES_Y = 1080;
  const TOP_MARGIN = 12;
  const BOTTOM_MARGIN = 24;

  function buildAssDanmu(options) {
    const input = options || {};
    const style = input.style || {};
    const fontSize = clamp(Number(style.fontSize) || 25, 8, 120);
    const speed = Math.max(3, Number(style.speed) || 8);
    const opacity = clamp(Number(style.opacity ?? 0.9), 0, 1);
    const maxLines = Math.round(clamp(Number(style.maxLines) || 15, 1, 60));
    const alpha = Math.round((1 - opacity) * 255);
    const alphaHex = hex2(alpha);
    const primary = assColor(normalizeHex(style.color) || "#ffffff", alphaHex);
    const laneHeight = Math.ceil(fontSize * 1.3) + 6;

    const lines = [
      "[Script Info]",
      "; Generated by 幕伴",
      `Title: ${oneLine(input.title || "Danmu")} - ${oneLine(input.episode || "")}`.replace(/\s+-\s*$/, ""),
      "ScriptType: v4.00+",
      `PlayResX: ${PLAY_RES_X}`,
      `PlayResY: ${PLAY_RES_Y}`,
      "AspectRatio: 16:9",
      "WrapStyle: 2",
      "ScaledBorderAndShadow: yes",
      "",
      "[V4+ Styles]",
      "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
      `Style: Danmu,Arial,${fontSize},${primary},&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2,0,8,0,0,${BOTTOM_MARGIN},1`,
      "",
      "[Events]",
      "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
    ];

    const lanes = { roll: [], top: [], bottom: [] };
    const comments = (input.comments || [])
      .map((item) => item && typeof item === "object" ? item : null)
      .filter(Boolean)
      .slice()
      .sort((a, b) => Number(a.time) - Number(b.time));

    for (const comment of comments) {
      const text = String(comment.text ?? "");
      if (!text.trim()) continue;

      const start = Math.max(0, Number(comment.time) || 0);
      const end = start + speed;
      const kind = kindFromMode(comment.mode);
      const lane = takeLane(lanes[kind], start, end, maxLines);
      const y = kind === "bottom"
        ? PLAY_RES_Y - BOTTOM_MARGIN - lane * laneHeight
        : TOP_MARGIN + lane * laneHeight;

      const size = clamp(Number(comment.fontSize) || fontSize, 8, 120);
      const color = normalizeHex(style.color || comment.color) || "#ffffff";
      const tags = [`\\an${kind === "bottom" ? 2 : 8}`];
      if (size !== fontSize) tags.push(`\\fs${size}`);
      if (color !== (normalizeHex(style.color) || "#ffffff")) tags.push(`\\c${assBgr(color)}`);
      if (kind === "roll") {
        const width = estimateWidth(text, size);
        const x1 = Math.round(PLAY_RES_X + width / 2);
        const x2 = Math.round(-width / 2);
        tags.push(`\\move(${x1},${Math.round(y)},${x2},${Math.round(y)})`);
      }

      lines.push(
        `Dialogue: 0,${assTime(start)},${assTime(end)},Danmu,,0,0,0,,{${tags.join("")}}${escapeAssText(text)}`
      );
    }

    return lines.join("\n");
  }

  function kindFromMode(mode) {
    if (mode === "bottom" || Number(mode) === 4) return "bottom";
    if (mode === "top" || Number(mode) === 5) return "top";
    return "roll";
  }

  function takeLane(state, start, end, maxLines) {
    for (let i = 0; i < state.length; i++) {
      if (state[i] <= start) {
        state[i] = end;
        return i;
      }
    }
    if (state.length < maxLines) {
      state.push(end);
      return state.length - 1;
    }
    let earliest = 0;
    for (let i = 1; i < state.length; i++) {
      if (state[i] < state[earliest]) earliest = i;
    }
    state[earliest] = end;
    return earliest;
  }

  function assTime(seconds) {
    const cs = Math.max(0, Math.round(Number(seconds) * 100));
    const h = Math.floor(cs / 360000);
    const m = Math.floor((cs % 360000) / 6000);
    const s = Math.floor((cs % 6000) / 100);
    const c = cs % 100;
    return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(c).padStart(2, "0")}`;
  }

  function normalizeHex(value) {
    if (!value) return null;
    let s = String(value).trim().replace(/^#/, "");
    if (/^[0-9a-f]{3}$/i.test(s)) s = s.split("").map((c) => c + c).join("");
    if (!/^[0-9a-f]{6}$/i.test(s)) return null;
    return `#${s.toLowerCase()}`;
  }

  function assColor(hex, alphaHex) {
    const bgr = hex.slice(1).match(/../g).reverse().join("").toUpperCase();
    return `&H${alphaHex}${bgr}`;
  }

  function assBgr(hex) {
    return `&H${hex.slice(1).match(/../g).reverse().join("").toUpperCase()}`;
  }

  function hex2(value) {
    return Math.max(0, Math.min(255, Math.round(value))).toString(16).padStart(2, "0").toUpperCase();
  }

  function estimateWidth(text, fontSize) {
    let units = 0;
    for (const ch of String(text)) {
      units += /[\u0000-\u00ff]/.test(ch) ? 0.55 : 1;
    }
    return Math.ceil(units * fontSize);
  }

  function escapeAssText(text) {
    return String(text)
      .replace(/\\/g, "\\\\")
      .replace(/\{/g, "\\{")
      .replace(/\}/g, "\\}")
      .replace(/,/g, "\\,")
      .replace(/\r?\n/g, "\\N");
  }

  function oneLine(value) {
    return String(value || "").replace(/[\r\n]+/g, " ").trim();
  }

  function clamp(value, min, max) {
    const n = Number(value);
    if (!Number.isFinite(n)) return min;
    return Math.max(min, Math.min(max, n));
  }

  global.buildAssDanmu = buildAssDanmu;
})(window);
